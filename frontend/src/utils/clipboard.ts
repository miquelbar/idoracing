/**
 * Copy text to the clipboard. `navigator.clipboard` only exists in secure contexts (https or localhost), so when the
 * app is opened over plain http from another machine (e.g. http://192.168.x.x:8501) it is undefined: fall back to a
 * hidden textarea + execCommand('copy'). Resolves to whether the copy succeeded.
 */
export async function copyText(text: string): Promise<boolean> {
  if (navigator.clipboard && window.isSecureContext) {
    try {
      await navigator.clipboard.writeText(text);
      return true;
    } catch {
      // fall through to the legacy path
    }
  }
  const area = document.createElement('textarea');
  area.value = text;
  area.setAttribute('readonly', '');
  area.style.position = 'fixed';
  area.style.top = '-1000px';
  area.style.opacity = '0';
  document.body.appendChild(area);
  area.select();
  area.setSelectionRange(0, text.length);
  let ok = false;
  try {
    ok = document.execCommand('copy');
  } catch {
    ok = false;
  }
  document.body.removeChild(area);
  return ok;
}
